#include "minishell.h"

void ft_pwd(void)
{
	char	cwd[4096];
	char	*path;

	path = getcwd(cwd, sizeof(cwd));
	if (!path)
	{
		perror("getcwd");
		return ;
	}
	ft_printf("%s\n", cwd);
}
